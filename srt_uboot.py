#!/usr/bin/env python3
"""The U-Boot installer for the Surface RT eMMC (design C); the command line help describes its use."""
import argparse
import os
import plistlib
import pwd
import re
import shutil
import socket
import struct
import subprocess
import sys
import time
from typing import NoReturn

import securet30sec_loader as stage
from securet30 import nvdauefi

HERE = os.path.dirname(os.path.abspath(__file__))
STUB = stage.read_header(os.path.join(HERE, 'payloads', 'uboot_stub.h'))[0]
STUB_BIN = os.path.join(HERE, 'payloads', 'uboot_stub.bin')    # generated by build.sh payloads, committed
IMAGES_DIR = os.path.join(HERE, 'out')                          # where build.sh puts its results
UBOOT_BIN = 'u-boot-dtb-tegra.bin'
D = nvdauefi.D
# The stub is written over the Pkcs7Verify entry, so the stage's own `bl Pkcs7Verify` runs it.
VERIFY_ENTRY = stage.SYMBOLS['Pkcs7Verify']

SECTOR = 512
BOOT_PARTITION_SIZE = 0x200000          # the Surface RT eMMC's boot0 and boot1
BACKUP_MAGIC = b'SRTUB001'
BACKUP_HDR = len(BACKUP_MAGIC) + 16 + 8    # magic + label + two u32 sizes

# bootstrap (the remote route): drive the device from the host over APX, fastboot and disk mode.
FUSEE = os.path.join(HERE, 'fusee-tools')              # the fusee-tools submodule (fusee gelee + tegrarcm)
DISKMODE_IMG = 'pmos-surface-rt-diskmode.img'          # in --images; the fastboot-booted disk-mode kernel
BOOTSTRAP_DEV_IP = '172.16.42.1'                       # the disk-mode device's USB-net address (pmOS unudhcpd)
BOOTSTRAP_FASTBOOT_WAIT = 90                           # s to wait for U-Boot's fastboot after the APX RAM-load
BOOTSTRAP_LUN_WAIT = 120                               # s to wait for the disk-mode mass-storage LUNs
BOOTSTRAP_REBOOT_WAIT = 90                             # s to wait for the device's USB-net to answer the reboot


def die(msg) -> NoReturn:
    sys.stderr.write('error: %s\n' % msg)
    sys.exit(1)


def confirm(question):
    try:
        return input('%s [y/N] ' % question).strip().lower() in ('y', 'yes')
    except EOFError:
        return False


# --- block-device access ---------------------------------------------------

def diskutil(*args):
    """macOS: the plist diskutil prints for `diskutil <args> -plist`."""
    out = subprocess.run(['diskutil', args[0], '-plist'] + list(args[1:]), capture_output=True, check=True).stdout
    return plistlib.loads(out)


def dev_size(path):
    """Size in bytes of a disk, from the OS's disk metadata (no need to open it), or of a regular file (a dump)."""
    if os.path.isfile(path):
        return os.path.getsize(path)
    if sys.platform == 'darwin':
        return diskutil('info', re.sub(r'^/dev/r?', '', path))['TotalSize']
    with open('/sys/class/block/%s/size' % os.path.basename(os.path.realpath(path))) as f:
        return int(f.read()) * 512                          # /sys counts 512-byte sectors


def raw(path):
    """The raw device for a macOS disk (/dev/diskN -> /dev/rdiskN); other paths unchanged."""
    m = re.match(r'/dev/(disk\d+)$', path) if sys.platform == 'darwin' else None
    return '/dev/r' + m.group(1) if m else path


def read_at(path, off, n):
    """n bytes at off, as one unbuffered read of whole sectors (raw devices take only aligned I/O)."""
    lo = off & ~(SECTOR - 1)
    hi = (off + n + SECTOR - 1) & ~(SECTOR - 1)
    with open(path, 'rb', buffering=0) as f:
        f.seek(lo)
        return f.read(hi - lo)[off - lo:off - lo + n]


def read_all(path):
    return read_at(path, 0, dev_size(path))


def patch(path, off, data):
    """Sector-aligned read-modify-write of `data` at byte `off`, then verify the read-back."""
    lo = off & ~(SECTOR - 1)
    hi = (off + len(data) + SECTOR - 1) & ~(SECTOR - 1)
    with open(path, 'r+b', buffering=0) as f:
        f.seek(lo)
        buf = bytearray(f.read(hi - lo))
        buf[off - lo:off - lo + len(data)] = data
        f.seek(lo)
        f.write(buf)
        os.fsync(f.fileno())
    if read_at(path, off, len(data)) != data:
        raise IOError('read-back mismatch at %s+%#x' % (path, off))


def write_whole(path, data):
    with open(path, 'r+b', buffering=0) as f:
        f.seek(0)
        f.write(data)
        os.fsync(f.fileno())
    if read_all(path)[:len(data)] != data:
        raise IOError('read-back mismatch on %s' % path)


# --- state -----------------------------------------------------------------

def classify(boot):
    """'pristine', 'installed', or 'unknown' for boot0's bytes, plus the entry list.

    Pristine (the factory layout): the backup image entry is the slot the stub reads U-Boot from, the image entry
    is not the stub, and UEFIDATA loads at the image entry's own load address. Installed: both image entries are
    the stub and UEFIDATA aims at Pkcs7Verify.
    """
    entries = nvdauefi.entries(boot)
    img, bak = (nvdauefi.entry(entries, D[t]) for t in ('NVDAUEFI_TYPE_IMAGE', 'NVDAUEFI_TYPE_IMAGE_BACKUP'))
    ud = nvdauefi.uefidata(boot, entries)
    if not img or not bak or ud is None:
        return 'unknown', entries
    load = nvdauefi.get(boot, ud, nvdauefi.UEFIDATA, 'load_address')
    stub_at = (nvdauefi.BOOT0, STUB['STUB_OFFSET'])
    if (bak['device'], bak['offset'], bak['size']) == (STUB['UBOOT_DEVICE'], STUB['UBOOT_OFFSET'],
                                                       STUB['UBOOT_SIZE']) \
            and (img['device'], img['offset']) != stub_at and load == img['load_address']:
        return 'pristine', entries
    if all((e['device'], e['offset']) == stub_at for e in (img, bak)) and load == VERIFY_ENTRY:
        return 'installed', entries
    return 'unknown', entries


# --- LUN discovery (only devices in the boot-partition format) ------------

def disks():
    """(path, size) of each whole disk: the external physical disks diskutil lists, as /dev/rdiskN, on macOS;
    /dev/sdX (and mmcblk, vd) on Linux."""
    if sys.platform == 'darwin':
        paths = ['/dev/r' + d for d in diskutil('list', 'external', 'physical')['WholeDisks']]
    else:
        # sd*/vd* and whole mmc disks are the USB mass-storage LUNs a host sees; mmcblkNboot[01] are the eMMC
        # boot partitions seen when the tool runs on the Surface RT itself (the local, non-bootstrap route).
        paths = ['/dev/' + n for n in sorted(os.listdir('/sys/block'))
                 if re.match(r'(sd[a-z]+|mmcblk\d+(boot[01])?|vd[a-z]+)$', n)]
    return [(p, dev_size(p)) for p in paths]


def ensure_writable(path):
    """On the Surface RT, an eMMC boot partition defaults to force_ro=1 and cannot be written; clear it. The
    host's USB mass-storage LUNs are already read-write (disk mode cleared force_ro), and dumps are plain files."""
    if sys.platform != 'linux' or os.path.isfile(path):
        return
    fro = '/sys/block/%s/force_ro' % os.path.basename(os.path.realpath(path))
    try:
        with open(fro) as f:
            if f.read().strip() == '0':
                return
        with open(fro, 'w') as f:
            f.write('0')
    except OSError:
        pass        # not a force_ro device, or no permission; a real write failure is reported where it happens


def find_luns(boot0_arg, boot1_arg):
    """Return (boot0_dev, boot1_dev): two boot partitions, boot0 with the NVDAUEFI table, boot1 without.

    Explicit args are checked the same way; without them both are auto-detected.
    """
    if boot0_arg or boot1_arg:
        if not (boot0_arg and boot1_arg):
            die('pass both --boot0 and --boot1, or neither')
        boot0_arg, boot1_arg = raw(boot0_arg), raw(boot1_arg)
        found = [boot0_arg, boot1_arg]
        for p in found:
            try:
                size = dev_size(p)
            except (OSError, subprocess.CalledProcessError) as e:
                die('%s: %s' % (p, e))
            if size != BOOT_PARTITION_SIZE:
                die('%s is %d bytes, not a Surface RT boot partition (%d)' % (p, size, BOOT_PARTITION_SIZE))
    else:
        seen = disks()
        found = [p for p, size in seen if size == BOOT_PARTITION_SIZE]
        if not found:
            die('no disk of exactly %d bytes; disks seen: %s' % (
                BOOT_PARTITION_SIZE, ', '.join('%s (%d bytes)' % d for d in seen) or 'none'))
    try:
        with_table = [p for p in found if nvdauefi.find_table(read_all(p)) is not None]
    except PermissionError as e:
        die('cannot read %s: %s (run under sudo)' % (e.filename, e.strerror))
    without = [p for p in found if p not in with_table]
    if len(with_table) != 1 or len(without) != 1:
        die('expected one boot partition with the NVDAUEFI table and one without, found %d and %d (%s); '
            'name them with --boot0/--boot1' % (len(with_table), len(without), ', '.join(found) or 'none'))
    if boot0_arg and with_table[0] != boot0_arg:
        die('--boot0 %s has no NVDAUEFI table but --boot1 %s has: swapped?' % (boot0_arg, boot1_arg))
    return with_table[0], without[0]


# --- backup / restore ------------------------------------------------------

def make_backup(boot0, boot1, path):
    b0 = read_all(boot0)
    b1 = read_all(boot1)
    header = BACKUP_MAGIC + b'surface-rt'.ljust(16, b'\0') + struct.pack('<II', len(b0), len(b1))
    with open(path, 'xb') as f:
        f.write(header)
        f.write(b0)
        f.write(b1)
        f.flush()
        os.fsync(f.fileno())
    # verify the host copy round-trips before we rely on it
    with open(path, 'rb') as f:
        rb = f.read()
    if rb[BACKUP_HDR:BACKUP_HDR + len(b0)] != b0 or rb[BACKUP_HDR + len(b0):] != b1:
        die('backup verification failed: %s' % path)
    return path


def load_backup(path):
    with open(path, 'rb') as f:
        blob = f.read()
    if blob[:len(BACKUP_MAGIC)] != BACKUP_MAGIC:
        die('not a Surface RT eMMC backup: %s' % path)
    n0, n1 = struct.unpack_from('<II', blob, len(BACKUP_MAGIC) + 16)
    b0 = blob[BACKUP_HDR:BACKUP_HDR + n0]
    b1 = blob[BACKUP_HDR + n0:BACKUP_HDR + n0 + n1]
    if len(b0) != n0 or len(b1) != n1:
        die('backup truncated: %s' % path)
    return b0, b1


def load_factory_backup(path):
    """boot0 and boot1 from a backup, which must hold the factory state (what uninstall restores)."""
    b0, b1 = load_backup(path)
    if nvdauefi.find_table(b0) is None or nvdauefi.find_table(b1) is not None:
        die('%s does not hold a Surface RT boot0 (with the NVDAUEFI table) and boot1 (without)' % path)
    if classify(b0)[0] != 'pristine':
        die('the backup\'s boot0 is not in the factory state (%s); restoring it would not uninstall'
            % classify(b0)[0])
    return b0, b1


# --- commands --------------------------------------------------------------

def cmd_status(b0, b1, args):
    state, entries = classify(read_all(b0))
    print('state: %s' % state)
    for e in entries:
        print('  %-18s device %d  offset %#9x  size %#9x  load %#x'
              % (nvdauefi.TYPE_NAMES.get(e['type'], 'type %#04x' % e['type']), e['device'], e['offset'],
                 e['size'], e['load_address']))

def cmd_backup(b0, b1, args):
    make_backup(b0, b1, args.backup)
    print('backed up boot0+boot1 to %s' % os.path.abspath(args.backup))


def cmd_install(b0, b1, args):
    boot = bytearray(read_all(b0))
    state, entries = classify(boot)
    if state == 'installed' and not args.reinstall:
        die('U-Boot is already installed; pass --reinstall to overwrite it in place, or uninstall first')
    if state not in ('pristine', 'installed'):
        die('eMMC is not in the factory state (image entry / UEFIDATA unexpected); refusing')
    if state == 'installed':
        print('reinstalling over the existing install (--reinstall): U-Boot and the stub are rewritten')
    img, bak = (nvdauefi.entry(entries, D[t]) for t in ('NVDAUEFI_TYPE_IMAGE', 'NVDAUEFI_TYPE_IMAGE_BACKUP'))
    ud = nvdauefi.uefidata(boot, entries)
    assert img and bak and ud is not None               # implied by 'pristine'
    uboot_bin = os.path.join(args.images, UBOOT_BIN)
    if not os.path.exists(uboot_bin):
        die('%s not found; build it with build.sh u-boot, or pass --images' % uboot_bin)
    uboot = read_all(uboot_bin)
    stub = read_all(args.stub)
    stub_size = -(-len(stub) // SECTOR) * SECTOR        # what read_image_block fetches for the stub
    if len(uboot) > STUB['UBOOT_SIZE']:
        die('U-Boot (%d bytes) does not fit the image slot (%#x)' % (len(uboot), STUB['UBOOT_SIZE']))
    empty = nvdauefi.entry(entries, D['NVDAUEFI_TYPE_EMPTY'])
    if not empty or empty['device'] != nvdauefi.BOOT0 or not \
            empty['offset'] <= STUB['STUB_OFFSET'] <= empty['offset'] + empty['size'] - stub_size:
        die('the stub (%#x bytes at boot0 %#x) does not fit the region the table marks empty'
            % (stub_size, STUB['STUB_OFFSET']))
    lun, lun_name = {nvdauefi.BOOT0: (b0, 'boot0'), nvdauefi.BOOT1: (b1, 'boot1')}[STUB['UBOOT_DEVICE']]
    plan = [(lun_name, lun, STUB['UBOOT_OFFSET'], uboot,
             'U-Boot (%s, %d bytes), over the backup UEFI image' % (uboot_bin, len(uboot))),
            ('boot0', b0, STUB['STUB_OFFSET'], stub,
             'loader stub (%s, %d bytes), in the empty region' % (os.path.basename(args.stub), len(stub)))]
    to_stub = (('device', nvdauefi.BOOT0, ''), ('offset', STUB['STUB_OFFSET'], ''), ('size', stub_size, ''))
    for what, base, layout, fields in (
            ('image entry', img['at'], nvdauefi.ENTRY, to_stub),
            ('backup image entry', bak['at'], nvdauefi.ENTRY, to_stub),
            # read_image_block reads image_size bytes, or backup_image_size on the watchdog-backup path
            ('UEFIDATA', ud, nvdauefi.UEFIDATA,
             (('load_address', VERIFY_ENTRY, ' (Pkcs7Verify)'), ('image_size', stub_size, ''),
              ('backup_image_size', stub_size, '')))):
        for name, value, note in fields:
            old = nvdauefi.get(boot, base, layout, name)
            if old == value:
                continue
            off, data = nvdauefi.put(boot, base, layout, name, value)
            plan.append(('boot0', b0, off, data, '%s %s: %#x -> %#x%s' % (what, name, old, value, note)))

    print('install will write:')
    for name, path, off, _, what in plan:
        print('  %s %-14s +%#08x  %s' % (name, path, off, what))
    if all(path != b1 for _, path, _, _, _ in plan):
        print('boot1 is not written; it keeps the factory UEFI image')
    if args.backup:
        print('after backing up boot0+boot1 to %s' % os.path.abspath(args.backup))
    elif state == 'pristine':
        print('no backup is taken (--backup FILE); uninstall needs one of the factory state')
    if not args.yes and not confirm('go ahead?'):
        die('aborted')
    if args.backup:
        make_backup(b0, b1, args.backup)
        print('backed up boot0+boot1 to %s' % os.path.abspath(args.backup))

    ensure_writable(b0)
    for _, path, off, data, _ in plan:
        patch(path, off, data)

    if classify(read_all(b0))[0] != 'installed':
        die('post-install check failed; restore the factory state with uninstall --backup')
    print('installed; the device boots U-Boot at the next cold boot.')


def cmd_uninstall(b0, b1, args):
    r0, r1 = load_factory_backup(args.backup)
    if len(r0) != dev_size(b0) or len(r1) != dev_size(b1):
        die('backup sizes (%d/%d) do not match the LUNs (%d/%d)' % (len(r0), len(r1), dev_size(b0), dev_size(b1)))
    print('uninstall will restore from %s:' % args.backup)
    print('  boot0 %-14s whole, %#x bytes (factory: both image entries, UEFIDATA, the backup UEFI image)'
          % (b0, len(r0)))
    print('  boot1 %-14s whole, %#x bytes' % (b1, len(r1)))
    if not args.yes and not confirm('go ahead?'):
        die('aborted')
    ensure_writable(b0)
    ensure_writable(b1)
    write_whole(b0, r0)
    write_whole(b1, r1)
    if classify(read_all(b0))[0] != 'pristine':
        die('post-restore check failed: boot0 is not in the factory state')
    print('restored; the device boots the UEFI image again.')


# --- bootstrap: the remote route -------------------------------------------

def _wait(timeout, probe):
    """Poll probe() once a second until it returns something truthy or timeout runs out; return it, or None."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        v = probe()
        if v:
            return v
        time.sleep(1)
    return None


def _invoking_user(args):
    """subprocess keyword arguments that run a tool as the user who invoked sudo, so that only the eMMC write keeps
    root. Run as root without sudo there is no such user: ask once, then the tools run as root."""
    uid = os.environ.get('SUDO_UID')
    if uid is None:
        print('running as root without sudo: fusee-launcher, tegrarcm and fastboot would run as root too')
        if not args.yes and not confirm('continue?'):
            die('aborted; start bootstrap with sudo from your user account')
        return {}
    pw = pwd.getpwuid(int(uid))
    gid = int(os.environ.get('SUDO_GID', pw.pw_gid))
    env = dict(os.environ, HOME=pw.pw_dir, USER=pw.pw_name, LOGNAME=pw.pw_name)
    if sys.platform == 'darwin':
        # pyusb finds libusb by name through ctypes.util.find_library, which on macOS takes the first match in
        # DYLD_FALLBACK_LIBRARY_PATH. sudo drops the user's value, so set one: the MacPorts and Apple-silicon
        # Homebrew library directories first, then dyld's defaults (setting the variable replaces them).
        env['DYLD_FALLBACK_LIBRARY_PATH'] = ':'.join(('/opt/local/lib', '/opt/homebrew/lib',
                                                      os.path.join(pw.pw_dir, 'lib'), '/usr/local/lib', '/lib',
                                                      '/usr/lib'))
    return dict(user=pw.pw_uid, group=gid, extra_groups=os.getgrouplist(pw.pw_name, gid), env=env)


def _fastboot_devices(fastboot, as_user):
    out = subprocess.run([fastboot, 'devices'], capture_output=True, text=True, **as_user).stdout
    return [line.split('\t')[0].split()[0] for line in out.splitlines() if line.strip()]


def _luns_present():
    """(boot0, boot1) if the two boot partitions are visible (one with the NVDAUEFI table, one without), else
    None. Quiet, for polling; find_luns is the authoritative, message-producing version."""
    found = [p for p, size in disks() if size == BOOT_PARTITION_SIZE]
    try:
        with_table = [p for p in found if nvdauefi.find_table(read_all(p)) is not None]
    except OSError:
        return None
    without = [p for p in found if p not in with_table]
    return (with_table[0], without[0]) if len(with_table) == 1 and len(without) == 1 else None


def _reboot_over_usbnet(ip, timeout):
    """Reboot the disk-mode device through its pmOS USB-net telnet (busybox telnetd hands us a login shell)."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            s = socket.create_connection((ip, 23), timeout=5)
        except OSError:
            time.sleep(2)
            continue
        try:
            time.sleep(1)
            s.sendall(b'reboot -f\n')
            time.sleep(1)
            s.sendall(b'echo b > /proc/sysrq-trigger\n')   # fallback if reboot is blocked
            time.sleep(1)
        finally:
            s.close()
        return True
    return False


def cmd_bootstrap(args):
    """From one APX entry, drive the whole install (or with --uninstall the restore) remotely: RAM-load U-Boot,
    fastboot-boot disk mode, write the eMMC over USB mass storage, and reboot. Started with sudo; the USB tools
    (fusee-launcher, tegrarcm, fastboot) run as the invoking user, so root stays with the LUN detection and the
    eMMC write."""
    if os.geteuid() != 0:
        die('bootstrap needs root (raw eMMC); run under sudo')
    if args.uninstall:
        load_factory_backup(args.backup)
    uboot = os.path.abspath(os.path.join(args.images, UBOOT_BIN))
    diskimg = os.path.join(args.images, DISKMODE_IMG)
    bct = os.path.abspath(args.bct or os.path.join(FUSEE, 'current.bct'))
    # fusee-tools' pieces (run_bootloader.sh stays for manual use; here we drive them ourselves so they run in
    # this interpreter's environment -- fusee-launcher needs pyusb, which the project provides).
    launcher = os.path.join(FUSEE, 'fusee-launcher-new', 'fusee-launcher.py')
    tegrarcm = os.path.join(FUSEE, 'tegrarcm', 'src', 'tegrarcm')
    patch_irom = os.path.join(FUSEE, 'payloads', 'out', 'T30', 'patch_irom.bin')
    miniloader = os.path.join(FUSEE, 'miniloaders', 'miniloader_t30_v1_13_patched.bin')
    fastboot = shutil.which('fastboot')
    if not fastboot:
        die('fastboot not found on PATH (Android platform-tools)')
    for path, what in ((uboot, 'U-Boot: build.sh u-boot'), (diskimg, 'disk-mode image: build.sh diskmode'),
                       (launcher, 'the fusee-tools submodule'), (tegrarcm, 'tegrarcm: build.sh tegrarcm'),
                       (patch_irom, 'fusee payload: build.sh fusee'), (miniloader, 'the fusee-tools submodule'),
                       (bct, 'a BCT: pass --bct, or dump one with fusee-tools/get_bct.sh')):
        if not os.path.exists(path):
            die('%s not found (%s)' % (path, what))
    import importlib.util
    if importlib.util.find_spec('usb') is None:
        die('pyusb not in this environment (fusee-launcher needs it); install it with: uv sync --group bootstrap')
    as_user = _invoking_user(args)

    print('==> Running fusee gelee (patch_irom) over APX')
    print('    If the device is not in APX: hold Volume-Up, tap Power, release Volume-Up, cable attached.')
    if subprocess.run([sys.executable, 'fusee-launcher-new/fusee-launcher.py', patch_irom],
                      cwd=FUSEE, **as_user).returncode != 0: # type: ignore
        die('fusee gelee failed; is the device in APX with an A-to-A data cable?')
    time.sleep(1)                       # let the payload bring the device back up for tegrarcm
    print('==> RAM-loading U-Boot with tegrarcm')
    if subprocess.run([tegrarcm, '--usb-timeout=0', '--bct', bct, '--bootloader', uboot,
                       '--miniloader', miniloader], cwd=FUSEE, **as_user).returncode != 0: # type: ignore
        die('tegrarcm failed to RAM-load U-Boot')

    print('==> Waiting for U-Boot to enter fastboot (up to %ds)' % BOOTSTRAP_FASTBOOT_WAIT)
    dev = _wait(BOOTSTRAP_FASTBOOT_WAIT, lambda: _fastboot_devices(fastboot, as_user) or None)
    if not dev:
        die('no fastboot device appeared; did U-Boot take the APX branch into fastboot?')
    print('    fastboot device: %s' % dev[0])

    print('==> Booting the disk-mode image over fastboot')
    if subprocess.run([fastboot, 'boot', diskimg], **as_user).returncode != 0: # type: ignore
        die('fastboot boot failed')

    print('==> Waiting for the disk-mode mass-storage LUNs (up to %ds)' % BOOTSTRAP_LUN_WAIT)
    pair = _wait(BOOTSTRAP_LUN_WAIT, _luns_present)
    if not pair:
        die('the eMMC LUNs did not appear; is the device in disk mode?')
    b0, b1 = pair
    print('    boot0 %-14s NVDAUEFI table at %#x' % (b0, nvdauefi.find_table(read_all(b0))))
    print('    boot1 %-14s no NVDAUEFI table' % b1)

    if args.no_install:
        print('==> --no-install: the device stays in disk mode.')
        return
    if args.uninstall:
        print('==> Restoring the factory state of the eMMC')
        cmd_uninstall(b0, b1, args)
    else:
        print('==> Installing U-Boot on the eMMC')
        cmd_install(b0, b1, args)

    if args.no_reboot:
        print('==> --no-reboot: hold Power to reboot the device when ready.')
        return
    print('==> Rebooting the device (over the disk-mode USB-net)')
    if not _reboot_over_usbnet(BOOTSTRAP_DEV_IP, BOOTSTRAP_REBOOT_WAIT):
        print('    could not reach the device at %s; hold Power to reboot it by hand.' % BOOTSTRAP_DEV_IP)


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog='srt_uboot', formatter_class=argparse.RawDescriptionHelpFormatter,
        description='Install, remove or bootstrap U-Boot on a Surface RT eMMC through the first\n'
                    "stage's pre-verification write: only boot0's unsigned NVDAUEFI metadata and\n"
                    'image slots are edited.',
        epilog='boot0 and boot1, the eMMC boot partitions, are found here:\n'
               '  on the Surface RT  /dev/mmcblk0boot0 and boot1 (force_ro cleared on write)\n'
               '  on a Linux host    /dev/sdX, the USB mass-storage LUNs of the device in\n'
               '                     disk mode (build.sh diskmode)\n'
               '  on a macOS host    /dev/rdiskN of those LUNs; macOS reports them as\n'
               '                     unreadable disks: choose Ignore, never Initialize\n'
               'Only disks of exactly the boot-partition size qualify, boot0 being the one\n'
               'with the NVDAUEFI table; --boot0/--boot1 name them explicitly. Reading them\n'
               'needs root, e.g. after uv sync:\n'
               '  sudo .venv/bin/python srt_uboot.py status')
    ap.add_argument('--boot0', help='boot0 LUN/device (default: auto-detect: the one with the NVDAUEFI table)')
    ap.add_argument('--boot1', help='boot1 LUN/device (default: auto-detect: the other one)')
    ap.add_argument('--images', metavar='DIR', default=IMAGES_DIR,
                    help='where to read U-Boot and the disk-mode image from (default: out/, from build.sh)')
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument('--backup', metavar='FILE',
                        help='the boot0+boot1 backup: backup writes it, as do install and bootstrap before writing '
                        '(once, at the first install); never over an existing file. uninstall and bootstrap '
                        '--uninstall restore from it')
    common.add_argument('--yes', action='store_true', help='do not prompt for confirmation')
    # install and bootstrap share the install options (bootstrap runs install at the end)
    install_opts = argparse.ArgumentParser(add_help=False, parents=[common])
    install_opts.add_argument('--stub', default=STUB_BIN, help='loader stub (default: payloads/uboot_stub.bin)')
    install_opts.add_argument('--reinstall', action='store_true',
                              help='rewrite U-Boot and the stub over an existing install instead of refusing')
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('status', parents=[common],
                   help='report whether the eMMC is pristine or has U-Boot installed, and list the NVDAUEFI table')
    sub.add_parser('backup', parents=[common],
                   help='copy boot0 + boot1 to the --backup file (the device keeps no copy)')
    sub.add_parser('install', parents=[install_opts], help='install U-Boot and the stub on boot0',
                   description="Write U-Boot over boot0's backup UEFI image and the stub into the empty boot0 "
                   'region, and repoint both image entries (normal and watchdog backup) and UEFIDATA so the first '
                   'stage runs the stub instead of verifying. boot1 is not written.')
    sub.add_parser('uninstall', parents=[common],
                   help='restore boot0 + boot1 from the --backup file of the factory state (UEFI boots again)')
    pbs = sub.add_parser('bootstrap', parents=[install_opts],
                         help='from one APX entry, remotely RAM-load U-Boot, boot disk mode, install (or '
                         'uninstall), and reboot',
                         description='From one APX entry: RAM-load U-Boot over APX (fusee-tools), which then enters '
                         'fastboot; fastboot-boot the disk-mode image; install over its mass-storage LUNs (or '
                         'uninstall with --uninstall); reboot the device over the disk-mode USB network. Needs the '
                         'results of build.sh, fastboot and '
                         'pyusb (uv sync --group bootstrap). Start it '
                         'with sudo: the USB tools run as the invoking user, only the LUN detection and the eMMC '
                         'write as root.')
    pbs.add_argument('--bct', help='Surface RT BCT for the APX RAM-load (default: fusee-tools/current.bct)')
    pbs.add_argument('--uninstall', action='store_true',
                     help='restore the factory state from --backup FILE instead of installing (UEFI boots again)')
    pbs.add_argument('--no-install', action='store_true',
                     help='stop once the device is in disk mode; write nothing, do not reboot')
    pbs.add_argument('--no-reboot', action='store_true', help='stop after writing the eMMC; do not reboot the device')
    args = ap.parse_args(argv)

    restores = args.cmd == 'uninstall' or (args.cmd == 'bootstrap' and args.uninstall)
    installs = args.cmd == 'install' or (args.cmd == 'bootstrap' and not args.uninstall and not args.no_install)
    if args.cmd == 'bootstrap':
        if args.uninstall and args.reinstall:
            ap.error('--uninstall and --reinstall exclude each other')
        if args.no_install and (args.uninstall or args.backup):
            ap.error('--no-install writes nothing: no --uninstall, no --backup')
    if args.backup:
        if restores and not os.path.exists(args.backup):
            die('backup %s not found' % args.backup)
        if (installs or args.cmd == 'backup') and os.path.exists(args.backup):
            die('backup %s already exists; not overwriting it' % args.backup)
    elif restores or args.cmd == 'backup':
        ap.error('%s needs --backup FILE' % ('bootstrap --uninstall' if args.cmd == 'bootstrap' else args.cmd))
    if installs and not os.path.exists(args.stub):
        die('stub %s not found; build it (build.sh payloads) or pass --stub' % args.stub)

    if args.cmd == 'bootstrap':
        cmd_bootstrap(args)
        return

    b0, b1 = find_luns(args.boot0, args.boot1)
    print('Surface RT eMMC boot partitions (%#x bytes each):' % BOOT_PARTITION_SIZE)
    print('  boot0 %-14s NVDAUEFI table at %#x' % (b0, nvdauefi.find_table(read_all(b0))))
    print('  boot1 %-14s no NVDAUEFI table' % b1)
    try:
        {'status': cmd_status, 'backup': cmd_backup, 'install': cmd_install, 'uninstall': cmd_uninstall}[args.cmd](
            b0, b1, args)
    except ValueError as e:                 # an inconsistent NVDAUEFI table, or a U-Boot setup not handled
        die(str(e))


if __name__ == '__main__':
    main()
