#!/bin/sh
# Builds an Android v0 boot image for the Microsoft Surface RT that U-Boot can boot via "fastboot boot":
# postmarketOS kernel (linux-postmarketos-grate), the plain (non-EFI) DTB, and a merged initramfs that drops
# into the pmOS debug shell in "disk mode": the debug shell exposes the eMMC to the USB host as mass storage
# (boot0/boot1 read-write, user area read-only) through pmOS's pmos.usb-storage= mechanism, extended to several
# LUNs by 0001-initramfs-usb-storage-multiple-luns.patch. The host then runs ../srt_uboot.py against those
# LUNs to back up and install/remove U-Boot. See ../README.md.
#
# The image carries no U-Boot, stub, installer or Python -- the host owns all of that; the initramfs only
# exposes the disk. The console debug shell stays up alongside disk mode; 0002-initramfs-debug-shell-console.patch
# keeps the kernel's console font and starts the on-screen keyboard after a countdown a key press skips.
#
# The initramfs is generated by the upstream armv7 mkinitfs, run under qemu-user in a chroot assembled from
# signed pmOS/Alpine packages.
#
# Requirements: root (chroot, mknod), curl, tar, openssl, python3, patch, fdtput (device-tree-compiler) and a
# statically linked qemu-arm (e.g. qemu-arm-static from qemu-user-static). Host: Linux x86_64 or aarch64. To run
# it without host root, run it as ../build.sh diskmode (in the container).
#
# Usage: build-pmos-surface-rt-diskmode.sh [output.img]
# Env:   WORK (default ./pmos-surface-rt-build), QEMU_ARM (default: from PATH)

set -eu

OUT=${1:-pmos-surface-rt-diskmode.img}
WORK=${WORK:-./pmos-surface-rt-build}
ALPINE=https://dl-cdn.alpinelinux.org/alpine/edge
PMOS=https://mirror.postmarketos.org/postmarketos
PMOS_KEY_URL=https://gitlab.postmarketos.org/postmarketOS/pmbootstrap/-/raw/main/pmb/data/keys/build.postmarketos.org.rsa.pub
MKBOOTIMG_URL="https://android.googlesource.com/platform/system/tools/mkbootimg/+/refs/heads/main/mkbootimg.py?format=TEXT"
DEVICE=device-microsoft-surface-rt
DTB=tegra30-microsoft-surface-rt.dtb

SELF=$(cd "$(dirname "$0")" && pwd)
# The eMMC LUNs disk mode exposes: boot0 and boot1 read-write (the installer writes them), the user area read-only
USB_STORAGE=/dev/mmcblk0boot0,/dev/mmcblk0boot1,/dev/mmcblk0:ro

# Load addresses match U-Boot's Tegra30 kernel_addr_r/fdt_addr_r/ramdisk_addr_r
BASE=0x80000000
KERNEL_OFFSET=0x02000000
SECOND_OFFSET=0x03000000
RAMDISK_OFFSET=0x03100000
TAGS_OFFSET=0x00000100

[ "$(id -u)" = 0 ] || { echo "error: must run as root (chroot)" >&2; exit 1; }
QEMU_ARM=${QEMU_ARM:-$(command -v qemu-arm-static || command -v qemu-arm || true)}
[ -n "$QEMU_ARM" ] || { echo "error: qemu-arm-static not found (set QEMU_ARM)" >&2; exit 1; }

case "$(uname -m)" in
	x86_64) HOST_ARCH=x86_64 ;;
	aarch64|arm64) HOST_ARCH=aarch64 ;;
	*) echo "error: unsupported host architecture $(uname -m)" >&2; exit 1 ;;
esac

mkdir -p "$WORK"
WORK=$(cd "$WORK" && pwd)
OUT=$(cd "$(dirname "$OUT")" && pwd)/$(basename "$OUT")
TOOLS=$WORK/tools
ROOT=$WORK/root
CACHE=$WORK/apk-cache
mkdir -p "$TOOLS" "$CACHE"

# $1: repo (main/community), $2: arch, $3: package -> file name of current version
alpine_pkg_file() {
	curl -fsSL "$ALPINE/$1/$2/APKINDEX.tar.gz" | tar -xzO APKINDEX 2>/dev/null |
		awk -v p="$3" '$0 == "P:" p { f = 1 } f && !done && /^V:/ { print p "-" substr($0, 3) ".apk"; done = 1 }'
}

# $1: package file, $2: target dir
extract_apk() {
	mkdir -p "$2"
	tar -xzf "$1" -C "$2" --warning=no-unknown-keyword 2>/dev/null
}

# --- Host tools: apk.static (signature-checked), host busybox, mkbootimg ---

rm -rf "$TOOLS"/*
for pkg in alpine-keys apk-tools-static busybox-static; do
	f=$(alpine_pkg_file main "$HOST_ARCH" "$pkg")
	[ -n "$f" ] || { echo "error: $pkg not found in Alpine edge" >&2; exit 1; }
	curl -fsSL -o "$TOOLS/$f" "$ALPINE/main/$HOST_ARCH/$f"
	extract_apk "$TOOLS/$f" "$TOOLS/$pkg"
done
APK_STATIC=$TOOLS/apk-tools-static/sbin/apk.static
sig=$(ls "$TOOLS"/apk-tools-static/sbin/apk.static.SIGN.RSA.sha256.*)
key=$(find "$TOOLS/alpine-keys/usr/share/apk/keys" -name "${sig##*apk.static.SIGN.RSA.sha256.}" | head -n 1)
[ -n "$key" ] || { echo "error: signing key for apk.static not found" >&2; exit 1; }
openssl dgst -sha256 -verify "$key" -signature "$sig" "$APK_STATIC" >/dev/null
echo "Verified $("$APK_STATIC" --version)"

mkdir -p "$TOOLS/gki/gki"
: > "$TOOLS/gki/gki/__init__.py"
printf 'def generate_gki_certificate(*args, **kwargs):\n    raise RuntimeError("GKI certificates are not supported here")\n' \
	> "$TOOLS/gki/gki/generate_gki_certificate.py"
curl -fsSL "$MKBOOTIMG_URL" | base64 -d > "$TOOLS/mkbootimg.py"
echo "Fetched host tools (busybox, mkbootimg)"

# --- armv7 root with merged /usr, like pmbootstrap creates it ---

rm -rf "$ROOT"
mkdir -p "$ROOT/etc/apk/keys" "$ROOT/usr/bin" "$ROOT/usr/sbin" "$ROOT/usr/lib"
ln -s usr/bin "$ROOT/bin"
ln -s usr/sbin "$ROOT/sbin"
ln -s usr/lib "$ROOT/lib"
cp "$TOOLS"/alpine-keys/usr/share/apk/keys/armv7/*.pub "$ROOT/etc/apk/keys/"
curl -fsSL -o "$ROOT/etc/apk/keys/build.postmarketos.org.rsa.pub" "$PMOS_KEY_URL"
cat > "$ROOT/etc/apk/repositories" <<EOF
$PMOS/extra-repos/systemd/master
$PMOS/master
$ALPINE/main
$ALPINE/community
EOF
echo armv7 > "$ROOT/etc/apk/arch"

APK="$APK_STATIC --root $ROOT --arch armv7 --cache-dir $CACHE --quiet"
$APK add --initdb --update-cache --no-scripts \
	alpine-baselayout systemd-udevd linux-postmarketos-grate \
	postmarketos-initramfs postmarketos-mkinitfs kmod-libs devmem2 2>&1 | grep -v 'redirected' || true
$APK info -e linux-postmarketos-grate postmarketos-initramfs >/dev/null ||
	{ echo "error: package installation failed" >&2; exit 1; }

# Device package without its dependencies (postmarketos-base, systemd-boot, ...)
$APK fetch -o "$WORK" "$DEVICE" 2>&1 | grep -v 'redirected' || true
extract_apk "$WORK/$DEVICE"-*.apk "$WORK/devpkg"
cp -a "$WORK/devpkg/usr" "$WORK/devpkg/etc" "$ROOT/"
rm -rf "$WORK/devpkg" "$WORK/$DEVICE"-*.apk
echo "Installed armv7 root: $("$APK_STATIC" --root "$ROOT" info -e -v linux-postmarketos-grate postmarketos-initramfs | tr '\n' ' ')"

# --- mkinitfs: merged initramfs ---

printf 'deviceinfo_create_initfs_extra="false"\n' > "$ROOT/etc/deviceinfo"

# Touchscreen and Type Cover touchpad are Win8 multitouch HID devices
# (group 0004); hid-multitouch drives them, hid-generic only falls back.
# udev loads it by modalias in stage 2.
mkdir -p "$ROOT/etc/mkinitfs/modules"
printf 'hid-multitouch\n' > "$ROOT/etc/mkinitfs/modules/50-surface-rt-input.modules"

# systemd-udevd loads modules through a dlopen()ed libkmod, which mkinitfs'
# ELF dependency scan cannot see; without it udev autoloads nothing. The
# merged initramfs skips stage 1's explicit module loading, so stage 2 relies
# on udev entirely.
mkdir -p "$ROOT/etc/mkinitfs/files"
printf '/usr/lib/libkmod.so.2\n' > "$ROOT/etc/mkinitfs/files/50-udev-libkmod.files"

# Boot-trace read-out (srt-boottrace): devmem2 and the layout it reads
mkdir -p "$ROOT/usr/share/srt"
cp "$SELF/../payloads/boottrace.h" "$SELF/../payloads/uboot_stub.h" "$ROOT/usr/share/srt/"
install -m 755 "$SELF/srt-boottrace" "$ROOT/usr/bin/srt-boottrace"
DEVMEM2=$(cd "$ROOT" && find usr/bin usr/sbin -name devmem2 | head -n 1)
[ -n "$DEVMEM2" ] || { echo "error: devmem2 not installed" >&2; exit 1; }
printf '/%s\n/usr/bin/srt-boottrace\n/usr/share/srt/boottrace.h\n/usr/share/srt/uboot_stub.h\n' "$DEVMEM2" \
	> "$ROOT/etc/mkinitfs/files/60-srt-boottrace.files"

# The initramfs file list requires /usr/lib/udev/udev.conf, which neither
# udev package ships; an empty file means udev defaults.
[ -e "$ROOT/usr/lib/udev/udev.conf" ] || : > "$ROOT/usr/lib/udev/udev.conf"

# postmarketos-initramfs patches, in order (see their headers): several pmos.usb-storage= LUNs, debug-shell console
for p in "$SELF"/00*-initramfs-*.patch; do
	patch -d "$ROOT" -p1 --forward < "$p" >/dev/null ||
		{ echo "error: $p does not apply to this postmarketos-initramfs" >&2; exit 1; }
	echo "Applied $(basename "$p")"
done

# mkinitfs deletes its output unless boot-deploy copies it out; boot-deploy is
# exec'd from the chroot, so the stand-in runs on the host busybox.
mkdir -p "$ROOT/hostbin" "$ROOT/out" "$ROOT/tmp" "$ROOT/dev"
cp "$TOOLS/busybox-static/bin/busybox.static" "$ROOT/hostbin/busybox"
cat > "$ROOT/usr/bin/boot-deploy" <<'EOF'
#!/hostbin/busybox sh
while getopts i:k:d:o: opt; do
	case $opt in
		d) in=$OPTARG ;;
		o) out=$OPTARG ;;
		*) ;;
	esac
done
/hostbin/busybox cp "$in/initramfs" "$out/initramfs"
EOF
chmod +x "$ROOT/usr/bin/boot-deploy"
[ -e "$ROOT/dev/null" ] || mknod -m 666 "$ROOT/dev/null" c 1 3
cp "$QEMU_ARM" "$ROOT/qemu-arm"

# The kernel package ships empty modules.dep/modules.alias and relies on its
# install trigger (skipped by --no-scripts) to run depmod.
KVER=$(ls "$ROOT/usr/lib/modules")
chroot "$ROOT" /qemu-arm /sbin/depmod "$KVER"
echo "Generated module index for $KVER"

chroot "$ROOT" /qemu-arm /usr/bin/mkinitfs -d /out > "$WORK/mkinitfs.log" 2>&1 ||
	{ cat "$WORK/mkinitfs.log" >&2; exit 1; }
echo "Generated initramfs ($(du -h "$ROOT/out/initramfs" | cut -f1))"

# --- device-tree: put the OTG port into peripheral mode ---

# The OTG port usb@7d000000 (the USB-A receptacle) is bound as nvidia,tegra30-ehci, a host-only controller.
# Rebind it to the Tegra ChipIdea device controller and make it peripheral-only:
# - dr_mode on the controller node: ChipIdea reads it there; without it, it runs OTG and picks its role from the
#   ID pin, which on this receptacle selects host.
# - dr_mode on the phy node: the Tegra PHY driver reads its own (VBUS detector on, ID detector off).
# - no vbus-supply on the phy: the PHY enables that regulator in every mode, which would drive the Surface's 5 V
#   against the host's on an A-to-A cable; usb1_vbus has no other consumer and is not always-on, so it stays off.
# The two other USB controllers are left as hosts.
DTB_OUT="$WORK/$DTB"
cp "$ROOT/boot/dtbs/$DTB" "$DTB_OUT"
fdtput -t s "$DTB_OUT" /usb@7d000000 compatible "nvidia,tegra30-udc"
fdtput -t s "$DTB_OUT" /usb@7d000000 dr_mode "peripheral"
fdtput -t s "$DTB_OUT" /usb-phy@7d000000 dr_mode "peripheral"
fdtput -d "$DTB_OUT" /usb-phy@7d000000 vbus-supply
echo "Patched $DTB: usb@7d000000 -> nvidia,tegra30-udc, peripheral-only, no VBUS drive"

# --- boot.img ---

# Device kernel command line without partition resizing, plus the debug shell in disk mode
CMDLINE=$(cat "$ROOT"/usr/lib/kernel-cmdline.d/*"$DEVICE"*.conf |
	grep -v -e '^#' -e '^pmos.force-partition-resize$' | tr '\n' ' ')
# mem=: Linux stays below the boot-trace log (../payloads/boottrace.h), so srt-boottrace reads it intact
TRACE_LOG=$(awk '$1 == "#define" && $2 == "BOOTTRACE_LOG" { print $3 }' "$SELF/../payloads/boottrace.h")
CMDLINE="${CMDLINE}console=tty0 pmos.debug-shell pmos.usb-storage=$USB_STORAGE mem=$(( (TRACE_LOG - BASE) >> 20 ))M"

PYTHONPATH="$TOOLS/gki" python3 "$TOOLS/mkbootimg.py" --header_version 0 \
	--kernel "$ROOT/boot/vmlinuz" \
	--ramdisk "$ROOT/out/initramfs" \
	--second "$DTB_OUT" \
	--base "$BASE" --kernel_offset "$KERNEL_OFFSET" \
	--second_offset "$SECOND_OFFSET" --ramdisk_offset "$RAMDISK_OFFSET" \
	--tags_offset "$TAGS_OFFSET" --pagesize 2048 \
	--cmdline "$CMDLINE" \
	-o "$OUT"
echo "Wrote $OUT"
echo "Command line: $CMDLINE"
